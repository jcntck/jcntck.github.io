import { test, expect } from '@playwright/test'
import type { Envelope } from '../../src/shared/storage/library'

test.skip(Boolean(process.env.PLAYWRIGHT_BASE_URL), 'Login e Drive simulados são exclusivos do ambiente local/CI; produção requer homologação real.')
test('registra, sincroniza, corrige e reabre leituras pelo mesmo estado compartilhado', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://accounts.google.com/gsi/client', route => route.fulfill({ contentType: 'application/javascript', body: `window.google={accounts:{oauth2:{initTokenClient:config=>({requestAccessToken:()=>config.callback({access_token:'synthetic-manga-drive',expires_in:3600,scope:'https://www.googleapis.com/auth/drive.file openid'})}),hasGrantedAllScopes:()=>true}}};` }))
  let remote: Envelope = { schemaVersion: 1, revision: 'original', diagnostics: { probe: { note: 'preserve' } }, modules: { another: { note: 'preserve' } }, extra: 'preserve' }
  let writes = 0
  await page.route('https://openidconnect.googleapis.com/v1/userinfo', route => route.fulfill({ json: { sub: 'test-google-A' } }))
  await page.route('https://www.googleapis.com/**', async route => {
    const request = route.request(); const url = new URL(request.url())
    if (request.method() === 'PATCH') { writes++; remote = request.postDataJSON() as Envelope; await route.fulfill({ json: {} }) }
    else if (url.pathname.endsWith('/about')) await route.fulfill({ json: { user: { permissionId: 'test-permission', displayName: 'Conta simulada' } } })
    else if (url.searchParams.get('alt') === 'media') await route.fulfill({ json: remote })
    else await route.fulfill({ json: { files: [{ id: 'test-file' }] } })
  })
  await page.goto('http://127.0.0.1:5175/tests/browser/fixtures/auth.html#/mangas')
  await expect(page.getByRole('link', { name: 'Mangás', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Entrar com Google' }).click()
  await expect(page.getByRole('heading', { name: 'Mangás', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cadastrar mangá', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Conectar Google Drive' }).click()
  await expect(page.getByText(/Ainda não há mangás cadastrados/)).toBeVisible()
  await page.getByRole('button', { name: 'Cadastrar o primeiro mangá' }).click()
  await page.getByLabel('Título', { exact: true }).fill('One Piece')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Último capítulo lido')).toBeFocused()
  await page.keyboard.type('Extra 1')
  await page.keyboard.press('Tab')
  await page.getByLabel('Data da leitura').fill('2026-04-06')
  await page.getByRole('button', { name: 'Preparar leitura' }).click()
  await expect(page.getByText('Pendente de sincronização', { exact: true })).toBeVisible()
  expect(writes).toBe(0)
  await page.getByRole('button', { name: 'Sincronizar', exact: true }).click()
  await expect(page.getByText('Confirmado no Drive', { exact: true })).toBeVisible()
  expect(writes).toBe(1)
  const first = (remote.modules.mangas as { items: { id: string; lastReadOn: string }[] }).items[0]
  await page.getByRole('button', { name: 'Fechar formulário' }).click()
  await page.screenshot({ path: testInfo.outputPath('mangas-library.png'), fullPage: true })
  await page.getByRole('button', { name: 'Corrigir leitura de One Piece' }).click()
  await page.getByLabel('Título', { exact: true }).fill('One Piece corrigido')
  await expect(page.getByLabel('Data da leitura')).toHaveValue('2026-04-06')
  await page.getByLabel('Sincronizar automaticamente nesta sessão').check()
  await page.getByRole('button', { name: 'Preparar leitura' }).click()
  await expect(page.getByText('Confirmado no Drive', { exact: true })).toBeVisible()
  expect(writes).toBe(2)
  expect(remote.diagnostics).toEqual({ probe: { note: 'preserve' } })
  expect(remote.modules.another).toEqual({ note: 'preserve' })
  expect(remote.extra).toBe('preserve')
  expect((remote.modules.mangas as { items: { id: string; lastReadOn: string }[] }).items[0]).toMatchObject({ id: first.id, lastReadOn: first.lastReadOn })
  await page.screenshot({ path: testInfo.outputPath('mangas-form.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Conexão', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Amostra retornada pelo Drive' })).toBeVisible()
  await page.getByRole('link', { name: 'Mangás', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One Piece corrigido' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Mangás', exact: true })).toBeVisible()
  await expect(page.getByText(/ainda não foram consultados/)).toBeVisible()
  await page.getByRole('button', { name: 'Conectar Google Drive' }).click()
  await expect(page.getByRole('heading', { name: 'One Piece corrigido' })).toBeVisible()
  await expect(page.getByText('06/04/2026')).toBeVisible()
  expect(writes).toBe(2)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('One Piece')
  expect(errors).toEqual([])
})
