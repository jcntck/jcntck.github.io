import { test, expect } from '@playwright/test'
import type { Envelope } from '../../src/shared/storage/library'

test.skip(Boolean(process.env.PLAYWRIGHT_BASE_URL), 'Login e Drive simulados são exclusivos do ambiente local/CI; produção requer homologação real.')
test('registra, sincroniza, corrige e reabre leituras pelo mesmo estado compartilhado', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://accounts.google.com/gsi/client', route => route.fulfill({ contentType: 'application/javascript', body: `window.google={accounts:{oauth2:{initTokenClient:config=>({requestAccessToken:()=>config.callback({access_token:'synthetic-manga-drive',expires_in:3600,scope:'https://www.googleapis.com/auth/drive.file openid'})}),hasGrantedAllScopes:()=>true}}};` }))
  let remote: Envelope = { schemaVersion: 1, revision: 'original', diagnostics: { probe: { note: 'preserve' } }, modules: { another: { note: 'preserve' } }, extra: 'preserve' }
  let writes = 0
  let driveRequests = 0
  let scanRequests = 0
  await page.route('https://scan.example/obra', route => { scanRequests++; return route.abort() })
  await page.route('https://openidconnect.googleapis.com/v1/userinfo', route => route.fulfill({ json: { sub: 'test-google-A' } }))
  await page.route('https://www.googleapis.com/**', async route => {
    driveRequests++
    const request = route.request(); const url = new URL(request.url())
    if (request.method() === 'PATCH') { writes++; remote = request.postDataJSON() as Envelope; await route.fulfill({ json: {} }) }
    else if (url.pathname.endsWith('/about')) await route.fulfill({ json: { user: { permissionId: 'test-permission', displayName: 'Conta simulada' } } })
    else if (url.searchParams.get('alt') === 'media') await route.fulfill({ json: remote })
    else await route.fulfill({ json: { files: [{ id: 'test-file' }] } })
  })
  await page.goto('http://127.0.0.1:5175/tests/browser/fixtures/auth.html#/mangas')
  await expect(page.getByRole('link', { name: 'Mangás', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Entrar com Google' }).click()
  await expect(page.getByRole('heading', { name: 'Mangás', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cadastrar mangá', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Conectar Google Drive' })).toHaveCount(0)
  await page.getByRole('link', { name: /Abrir Conexão/ }).click()
  await page.getByRole('button', { name: 'Conectar Google Drive' }).click()
  await expect(page.getByText('Conta conectada e documento conferido.')).toBeVisible()
  await page.getByLabel('Sincronizar automaticamente nesta sessão').check()
  await page.getByRole('link', { name: 'Mangás', exact: true }).click()
  await expect(page.getByLabel('Sincronizar automaticamente nesta sessão')).toHaveCount(0)
  const beforeEdits = driveRequests
  await page.clock.install()
  await page.getByRole('button', { name: 'Cadastrar o primeiro mangá' }).click()
  expect(await page.getByRole('form').evaluate(element => getComputedStyle(element).animationName)).not.toBe('none')
  await page.getByLabel('Título', { exact: true }).fill('One Piece')
  await page.getByLabel('Nome em inglês (opcional)').fill('Pirate Adventure')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Último capítulo lido')).toBeFocused()
  await page.keyboard.type('Extra 1')
  await page.keyboard.press('Tab')
  await page.getByLabel('Data da leitura').fill('2026-04-06')
  await page.getByLabel('Link da scan (opcional)').fill('https://scan.example/obra')
  await page.getByLabel('Nome da scan (opcional)').fill('Scan de teste')
  await page.getByRole('button', { name: 'Salvar leitura' }).click()
  await expect(page.getByRole('form')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'One Piece', exact: true })).toBeFocused()
  await expect(page.getByText('Pendente de sincronização', { exact: true })).toBeVisible()
  expect(writes).toBe(0)
  await page.clock.runFor(1200)
  await page.getByRole('button', { name: 'Cadastrar mangá', exact: true }).click()
  await page.getByLabel('Título', { exact: true }).fill('Árvore')
  await page.getByLabel('Último capítulo lido').fill('12.5')
  await page.getByLabel('Data da leitura').fill('2025-12-01')
  await page.getByLabel('Link da scan (opcional)').fill('https://scan.example/obra')
  await page.getByRole('button', { name: 'Salvar leitura' }).click()
  await page.clock.runFor(1200)
  expect(writes).toBe(0)
  expect(driveRequests).toBe(beforeEdits)
  expect(scanRequests).toBe(0)
  const titles = () => page.locator('.manga-list h3').allTextContents()
  await expect(page.getByRole('link', { name: 'Ler Árvore em scan.example (abre em nova aba)' })).toBeVisible()
  expect(await titles()).toEqual(['Árvore', 'One Piece'])
  await page.getByLabel('Ordenar por').selectOption('title-desc')
  expect(await titles()).toEqual(['One Piece', 'Árvore'])
  await page.getByLabel('Ordenar por').selectOption('date-asc')
  expect(await titles()).toEqual(['Árvore', 'One Piece'])
  await page.getByLabel('Ordenar por').selectOption('date-desc')
  expect(await titles()).toEqual(['One Piece', 'Árvore'])
  await page.getByLabel('Buscar mangá').fill('ARVORE')
  expect(await titles()).toEqual(['Árvore'])
  await page.getByLabel('Buscar mangá').fill('PIRATE ADVENTURE')
  expect(await titles()).toEqual(['One Piece'])
  await expect(page.getByText('Pirate Adventure', { exact: true })).toBeVisible()
  await page.getByLabel('Buscar mangá').fill('ausente')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra encontrada.' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar busca' }).click()
  await expect(page.getByRole('link', { name: 'Ler One Piece em Scan de teste (abre em nova aba)' })).toHaveAttribute('href', 'https://scan.example/obra')
  await expect(page.getByRole('button', { name: /Verificar link/ })).toHaveCount(0)
  const footer = page.getByRole('button', { name: 'Editar One Piece', exact: true }).locator('..')
  await expect(footer.getByRole('link', { name: /Ler One Piece em Scan de teste/ })).toBeVisible()
  const linkBox = await footer.getByRole('link').boundingBox()
  const editBox = await footer.getByRole('button', { name: 'Editar One Piece', exact: true }).boundingBox()
  expect(Math.abs((linkBox!.y + linkBox!.height / 2) - (editBox!.y + editBox!.height / 2))).toBeLessThan(3)
  expect(scanRequests).toBe(0)
  expect(driveRequests).toBe(beforeEdits)
  await page.getByRole('button', { name: 'Sincronizar', exact: true }).click()
  await expect(page.getByText('Confirmado no Drive', { exact: true })).toHaveCount(2)
  expect(writes).toBe(1)
  const first = (remote.modules.mangas as { items: { id: string; lastReadOn: string }[] }).items[0]
  await expect(page.getByRole('form')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('mangas-library.png'), fullPage: true })
  await page.getByLabel('Buscar mangá').fill('ONE PIECE')
  await page.getByRole('button', { name: 'Editar One Piece' }).click()
  await page.getByLabel('Título', { exact: true }).fill('One Piece corrigido')
  await expect(page.getByLabel('Data da leitura')).toHaveValue('2026-04-06')
  await expect(page.getByLabel('Nome da scan (opcional)')).toHaveValue('Scan de teste')
  await page.screenshot({ path: testInfo.outputPath('mangas-form.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Salvar leitura' }).click()
  await expect(page.getByRole('form')).toHaveCount(0)
  await expect(page.getByLabel('Buscar mangá')).toHaveValue('')
  await expect(page.getByRole('heading', { name: 'One Piece corrigido' })).toBeFocused()
  const beforeCorrection = driveRequests
  await page.clock.runFor(1500)
  expect(writes).toBe(1)
  expect(driveRequests).toBe(beforeCorrection)
  await expect(page.getByText('Pendente de sincronização', { exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Sincronizar', exact: true }).click()
  await expect(page.getByText('Confirmado no Drive', { exact: true })).toHaveCount(2)
  expect(writes).toBe(2)
  expect(remote.diagnostics).toEqual({ probe: { note: 'preserve' } })
  expect(remote.modules.another).toEqual({ note: 'preserve' })
  expect(remote.extra).toBe('preserve')
  expect((remote.modules.mangas as { items: { scanUrl?: string }[] }).items[0].scanUrl).toBe('https://scan.example/obra')
  expect((remote.modules.mangas as { items: { englishTitle?: string }[] }).items[0].englishTitle).toBe('Pirate Adventure')
  expect((remote.modules.mangas as { items: { id: string; lastReadOn: string }[] }).items[0]).toMatchObject({ id: first.id, lastReadOn: first.lastReadOn })
  await expect(page.getByRole('form')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Conexão', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Amostra retornada pelo Drive' })).toBeVisible()
  await page.getByRole('link', { name: 'Mangás', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One Piece corrigido' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Mangás', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('Drive desconectado')
  await page.getByRole('link', { name: /Abrir Conexão/ }).click()
  await page.getByRole('button', { name: 'Conectar Google Drive' }).click()
  await expect(page.getByText('Conta conectada e documento conferido.')).toBeVisible()
  await page.getByRole('link', { name: 'Mangás', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'One Piece corrigido' })).toBeVisible()
  await expect(page.getByText('06/04/2026')).toBeVisible()
  await expect(page.getByText('Pirate Adventure', { exact: true })).toBeVisible()
  expect(writes).toBe(2)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('One Piece')
  expect(scanRequests).toBe(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Editar One Piece corrigido' }).click()
  expect(await page.getByRole('form').evaluate(element => getComputedStyle(element).animationName)).toBe('none')
  expect(await page.getByRole('button', { name: 'Salvar leitura' }).evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  await page.getByRole('button', { name: 'Fechar formulário' }).click()
  await expect(page.getByRole('button', { name: 'Cadastrar mangá', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Editar One Piece corrigido' }).click()
  await page.getByLabel('Nome da scan (opcional)').fill('NomeDaScan'.repeat(30))
  await page.getByLabel('Nome em inglês (opcional)').fill('LongEnglishTitle'.repeat(30))
  await page.getByRole('button', { name: 'Salvar leitura' }).click()
  await expect(page.getByRole('form')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(writes).toBe(2)
  expect(errors).toEqual([])
})
